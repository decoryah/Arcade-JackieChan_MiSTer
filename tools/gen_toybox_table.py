#!/usr/bin/env python3
"""Writes rtl/jchan_toybox_tbl.svh: the toybox data-ROM "decryption" table of kaneko_toybox.cpp as an SV function.

  python tools/gen_toybox_table.py

The table is read from the pinned MAME source (ref/mame/.../kaneko_toybox.cpp) through tools/toybox_model.py, so the RTL and the model
cannot disagree about it.  jchan uses decryption_table (GAME_NORMAL / TABLE_NORMAL); decryption_table_alt is Bonk's Adventure only.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import paths  # noqa: E402
import toybox_model as T  # noqa: E402


def main(argv):
    tbl = T.parse_tables()['decryption_table']
    out = os.path.join(paths.REPO, 'rtl', 'jchan_toybox_tbl.svh')
    with open(out, 'w', newline='\n') as f:
        f.write('// Generated by tools/gen_toybox_table.py from kaneko_toybox.cpp (decryption_table); do not edit.\n')
        f.write('function automatic [7:0] tb_dtab(input [7:0] i);\n    case (i)\n')
        for i, v in enumerate(tbl):
            f.write("        8'd%d: tb_dtab = 8'h%02x;\n" % (i, v))
        f.write("        default: tb_dtab = 8'h00;\n    endcase\nendfunction\n")
    print('wrote', out)
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
