#!/usr/bin/env python3
"""YMZ280B reference: MAME's own chip code (devices/sound/ymz280b.cpp, 0.289) built into a small C++ harness, driven by a register-write log.

The harness is *generated* from the pinned MAME source every time: the voice struct, the ADPCM / PCM8 / PCM16 decoders, the register writes, the
level / pan maths and `sound_stream_update` are cut out of the file verbatim (no re-typing), and wrapped in a few stubs (the device base classes,
`sound_stream`, `emu_timer`, a ROM array).  It replays what MAME's sound system does around the chip:

  * a data-port write first updates the stream up to and including the sample index of its time (`sound_stream::update`: idx - written + 1 samples),
    then executes the register write; an address-port write does not update;
  * the sound manager updates every stream every 1/50 s (STREAMS_UPDATE_FREQUENCY);
  * the stream rate is the integer part of clock / 384 * 2 = 83333 Hz.

Output: the per-sample stereo sums of the voices' `interp * level / 2` integers (what MAME hands to `stream.add_int(..., 32768 * 256)`), int32 pairs.

  python tools/ymz_ref.py build                      build the harness only
  python tools/ymz_ref.py run <set> [--seconds 70]   replay work/sound/<set>.ymlog.txt, write work/sound/<set>.ref.i32
Library use: events_from_log(), run(rom_bytes_path, events, nsamples) -> array('i') of interleaved L R.
"""
import argparse
import array
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import paths  # noqa: E402

RATE = 83333                      # int(16 MHz / 384 * 2)
SRC = os.path.join(paths.BASE, 'ref', 'mame', 'src', 'devices', 'sound', 'ymz280b.cpp')
GEN = os.path.join(paths.BASE, 'work', 'xcheck')
EXE = os.path.join(GEN, 'ymz_harness')

STUB_HEAD = r'''
// GENERATED by tools/ymz_ref.py from ymz280b.cpp -- the chip code below the marker is MAME's, verbatim.
#include <cstdint>
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <memory>
#include <vector>
#include <iterator>
#include <algorithm>
typedef uint8_t u8; typedef uint16_t u16; typedef uint32_t u32; typedef uint64_t u64;
typedef int8_t s8; typedef int16_t s16; typedef int32_t s32; typedef int64_t s64;
#define logerror(...) do {} while (0)
struct attotime { static const attotime zero; };
const attotime attotime::zero = {};
struct emu_timer { bool fired = false; void adjust(attotime, int) { fired = true; } };
struct sound_stream {
    int n = 0;
    std::vector<s64> L, R;
    int samples() const { return n; }
    void add_int(int ch, int idx, int val, int) { (ch ? R : L)[idx] += val; }
};
typedef uint32_t offs_t;
static std::vector<u8> g_rom;
struct devcb_stub { bool isunset() const { return true; } void operator()(int) {} };

class ymz280b_device {
public:
    struct YMZ280BVoice {
        u8 playing; bool ended; u8 keyon; u8 looping; u8 mode; u16 fnum; u8 level; u8 pan;
        u32 start; u32 stop; u32 loop_start; u32 loop_end; u32 position;
        s32 signal; s32 step; s32 loop_signal; s32 loop_step; u32 loop_count;
        s32 output_left; s32 output_right; s32 output_step; s32 output_pos;
        s16 last_sample; s16 curr_sample; u8 irq_schedule;
        emu_timer *timer;
    };
    void update_irq_state();
    void update_step(YMZ280BVoice *voice);
    void update_volumes(YMZ280BVoice *voice);
    void update_irq_state_timer_common(int param);
    int generate_adpcm(YMZ280BVoice *voice, s16 *buffer, int samples);
    int generate_pcm8(YMZ280BVoice *voice, s16 *buffer, int samples);
    int generate_pcm16(YMZ280BVoice *voice, s16 *buffer, int samples);
    void write_to_register(int data);
    void sound_stream_update(sound_stream &stream);

    YMZ280BVoice m_voice[8];
    u8 m_current_register = 0, m_status_register = 0, m_irq_state = 0, m_irq_mask = 0, m_irq_enable = 0, m_keyon_enable = 0, m_ext_mem_enable = 0;
    u8 m_ext_readlatch = 0;
    u32 m_ext_mem_address_hi = 0, m_ext_mem_address_mid = 0, m_ext_mem_address = 0;
    devcb_stub m_irq_handler;
    double m_master_clock = 16000000.0 / 384.0;
    std::unique_ptr<s16[]> m_scratch;
    emu_timer m_timers[8];

    u8 read_byte(u32 a) const { a &= 0xffffff; return a < g_rom.size() ? g_rom[a] : 0; }
    struct { void write_byte(u32, u8) {} } m_space;
    auto &space(int) { return m_space; }
    void init() {
        memset(m_voice, 0, sizeof m_voice);
        for (int i = 0; i < 8; i++) m_voice[i].timer = &m_timers[i];
        m_scratch = std::make_unique<s16[]>(10000);
    }
    void reset();
    // the harness side
    void pump_timers() { for (int i = 0; i < 8; i++) if (m_timers[i].fired) { m_timers[i].fired = false; update_irq_state_timer_common(i); } }
};
'''

DEVICE_RESET = r'''
void ymz280b_device::reset()
{
    // device_reset(), verbatim logic (clear all registers by writing 0, highest first)
    for (int i = 0xff; i >= 0; i--) { m_current_register = i; write_to_register(0); }
    m_current_register = 0; m_status_register = 0; m_ext_mem_address = 0;
    for (auto &elem : m_voice) { YMZ280BVoice *voice = &elem; voice->curr_sample = 0; voice->last_sample = 0; voice->output_pos = FRAC_ONE; voice->playing = 0; }
}
'''

MAIN = r'''
int main(int argc, char** argv)
{
    // ymz_harness <rom.bin> <events.txt> <nsamples> <out.i32>
    if (argc < 5) return 2;
    FILE* f = fopen(argv[1], "rb"); if (!f) return 3;
    fseek(f, 0, SEEK_END); long n = ftell(f); fseek(f, 0, SEEK_SET);
    g_rom.resize(n); if (fread(g_rom.data(), 1, n, f) != (size_t)n) return 3; fclose(f);
    long nsamples = atol(argv[3]);
    FILE* fe = fopen(argv[2], "r"); if (!fe) return 4;
    FILE* fo = fopen(argv[4], "wb"); if (!fo) return 5;
    compute_tables();
    ymz280b_device d; d.init(); d.reset();
    long written = 0;
    sound_stream st;
    auto gen = [&](long count) {
        while (count > 0) {
            long c = count > 4096 ? 4096 : count;
            st.n = (int)c; st.L.assign(c, 0); st.R.assign(c, 0);
            d.sound_stream_update(st);
            for (long i = 0; i < c; i++) { int32_t v[2] = { (int32_t)st.L[i], (int32_t)st.R[i] }; fwrite(v, 4, 2, fo); }
            written += c; count -= c;
        }
    };
    // NOTE: chunking at 4096 only splits a long update for buffer size; MAME's chunk is the whole interval, so keep them equal by generating
    // an update as ONE call (the vectors are sized for it)
    char line[128];
    while (fgets(line, sizeof line, fe)) {
        long idx; int kind; unsigned val;
        if (sscanf(line, "%ld %d %x", &idx, &kind, &val) != 3) continue;
        if (idx >= nsamples) break;
        long cnt = idx - written + 1;
        if (cnt > 0) {
            if (getenv("YMZ_DBG") && written <= atol(getenv("YMZ_DBG")) && idx >= atol(getenv("YMZ_DBG"))) {
                printf("update: samples %ld .. %ld  (event idx %ld kind %d)\n", written, idx, idx, kind);
                for (int v = 0; v < 8; v++) {
                    auto &w = d.m_voice[v];
                    printf("  v%d play=%d mode=%d keyon=%d loop=%d fnum=%03x pos=%d opos=%d prev=%d curr=%d position=%u stop=%u lend=%u signal=%d step=%d level=%d pan=%d\n", v, w.playing, w.mode, w.keyon, w.looping, w.fnum, w.output_pos, w.output_pos, w.last_sample, w.curr_sample, w.position, w.stop, w.loop_end, w.signal, w.step, w.level, w.pan);
                }
            }
            if (getenv("YMZ_DBG") && written <= atol(getenv("YMZ_DBG")) && idx >= atol(getenv("YMZ_DBG"))) {
                // debugging only: the chunk one sample at a time (state of every voice around the sample of interest)
                long S = atol(getenv("YMZ_DBG"));
                for (long k = 0; k < cnt; k++) {
                    st.n = 1; st.L.assign(1, 0); st.R.assign(1, 0);
                    d.sound_stream_update(st);
                    int32_t v[2] = { (int32_t)st.L[0], (int32_t)st.R[0] }; fwrite(v, 4, 2, fo);
                    written++;
                    if (written - 1 >= S - 2 && written - 1 <= S + 2) {
                        printf("after sample %ld: out %d / %d\n", written - 1, v[0], v[1]);
                        for (int q = 0; q < 8; q++) {
                            auto &w = d.m_voice[q];
                            if (w.playing || w.last_sample || w.curr_sample)
                                printf("  v%d play=%d opos=%d prev=%d curr=%d position=%u signal=%d step=%d lcount=%u lsig=%d lstep=%d\n", q, w.playing, w.output_pos, w.last_sample, w.curr_sample, w.position, w.signal, w.step, w.loop_count, w.loop_signal, w.loop_step);
                        }
                    }
                }
            } else {
            st.n = (int)cnt; st.L.assign(cnt, 0); st.R.assign(cnt, 0);
            d.sound_stream_update(st);
            for (long i = 0; i < cnt; i++) { int32_t v[2] = { (int32_t)st.L[i], (int32_t)st.R[i] }; fwrite(v, 4, 2, fo); }
            written += cnt;
            }
            d.pump_timers();      // the end-of-sample timers fire before the next CPU instruction
        }
        if (kind == 0) d.m_current_register = (u8)val;
        else if (kind == 1) { d.write_to_register((int)val); d.pump_timers(); }
        // kind 2: the 1/50 s timer: nothing but the update above
    }
    long cnt = nsamples - written;
    if (cnt > 0) {
        st.n = (int)cnt; st.L.assign(cnt, 0); st.R.assign(cnt, 0);
        d.sound_stream_update(st);
        for (long i = 0; i < cnt; i++) { int32_t v[2] = { (int32_t)st.L[i], (int32_t)st.R[i] }; fwrite(v, 4, 2, fo); }
    }
    fclose(fo);
    return 0;
}
'''


def extract(src, pattern):
    """The text of the first function whose head matches `pattern`, up to the closing brace at column 0."""
    m = re.search(pattern, src, re.M)
    if not m:
        raise SystemExit('ymz_ref: cannot find %s in %s' % (pattern, SRC))
    start = m.start()
    end = src.index('\n}\n', start) + 3
    return src[start:end]


def generate():
    src = open(SRC, encoding='utf-8').read()
    parts = []
    # constants and tables at the top of the file
    a = src.index('#define MAX_SAMPLE_CHUNK')
    b = src.index('static int diff_lookup[16];') + len('static int diff_lookup[16];')
    parts.append(src[a:b].replace('#define INTERNAL_SAMPLE_RATE    (m_master_clock * 2.0)', ''))
    parts.append(extract(src, r'^void ymz280b_device::update_step\('))
    parts.append(extract(src, r'^void ymz280b_device::update_volumes\('))
    parts.append(extract(src, r'^static void compute_tables\('))
    parts.append(extract(src, r'^int ymz280b_device::generate_adpcm\('))
    parts.append(extract(src, r'^int ymz280b_device::generate_pcm8\('))
    parts.append(extract(src, r'^int ymz280b_device::generate_pcm16\('))
    parts.append(extract(src, r'^void ymz280b_device::sound_stream_update\('))
    parts.append(extract(src, r'^void ymz280b_device::write_to_register\('))
    # the timer callback is a TIMER_CALLBACK_MEMBER; irq state needs the stub handler
    parts.append(extract(src, r'^void ymz280b_device::update_irq_state\(\)'))
    tcb = extract(src, r'^TIMER_CALLBACK_MEMBER\(ymz280b_device::update_irq_state_timer_common\)')
    tcb = tcb.replace('TIMER_CALLBACK_MEMBER(ymz280b_device::update_irq_state_timer_common)', 'void ymz280b_device::update_irq_state_timer_common(int param)')
    parts.append(tcb)
    body = '\n'.join(parts)
    # the stream API of sound_stream_update: stream.samples(), stream.add_int()
    body = body.replace('stream.add_int(0, sampindex, interp_sample * lvol / 2, 32768 * 256);', 'stream.add_int(0, sampindex, interp_sample * lvol / 2, 32768 * 256);')
    text = STUB_HEAD + '\n// ---- MAME 0.289 ymz280b.cpp, verbatim ----\n' + body + '\n// ---- end of MAME code ----\n' + DEVICE_RESET + MAIN
    if not os.path.isdir(GEN):
        os.makedirs(GEN)
    p = os.path.join(GEN, 'ymz_harness_gen.cpp')
    open(p, 'w', encoding='utf-8', newline='\n').write(text)
    return p


def build():
    p = generate()
    r = subprocess.run(['wsl', '-e', 'bash', '-lc', "g++ -O2 -std=c++17 -o '%s' '%s'" % (paths.wsl(EXE), paths.wsl(p))],
                       stdout=subprocess.PIPE, stderr=subprocess.STDOUT, universal_newlines=True)
    if r.returncode:
        print(r.stdout[-3000:])
        raise SystemExit('harness build failed')
    return EXE


def events_from_log(path, max_seconds=None):
    """work/sound/<set>.ymlog.txt -> [(idx, kind, val)]  kind 0 = register select, 1 = data write, 2 = 1/50 s update; sorted by time."""
    ev = []
    last_ns = 0
    for line in open(path):
        t, o, d, _f = line.split()
        sec, _, frac = t.replace(',', '.').partition('.')
        ns = int(sec) * 10 ** 9 + int((frac + '000000000')[:9])
        if max_seconds is not None and ns > max_seconds * 10 ** 9:
            break
        ev.append((ns, 0, int(o), int(d, 16)))
        last_ns = ns
    k = 1
    while k * 20000000 <= last_ns:
        ev.append((k * 20000000, 1, 2, 0))
        k += 1
    ev.sort(key=lambda e: (e[0], e[1]))      # stable: writes keep their order; a timer at the same instant goes after (rare)
    out = []
    for ns, _o, kind, val in ev:
        out.append((ns * RATE // 10 ** 9, kind if kind != 2 else 2, val))
    # offset 0 -> kind 0, offset 1 -> kind 1
    return out


def run(rom_path, events, nsamples, out_path=None):
    exe = EXE if os.path.exists(EXE) else build()
    ev_path = os.path.join(GEN, 'events.txt')
    with open(ev_path, 'w') as f:
        for idx, kind, val in events:
            f.write('%d %d %x\n' % (idx, kind, val))
    out = out_path or os.path.join(GEN, 'ymz_ref.i32')
    r = subprocess.run(['wsl', '-e', exe and paths.wsl(exe), paths.wsl(rom_path), paths.wsl(ev_path), str(nsamples), paths.wsl(out)],
                       stdout=subprocess.PIPE, stderr=subprocess.STDOUT, universal_newlines=True)
    if r.returncode:
        raise SystemExit('harness failed: %s' % r.stdout[-500:])
    a = array.array('i')
    with open(out, 'rb') as f:
        a.frombytes(f.read())
    return a


def main(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument('cmd', choices=['build', 'run'])
    ap.add_argument('set', nargs='?')
    ap.add_argument('--seconds', type=float, default=70.0)
    a = ap.parse_args(argv)
    if a.cmd == 'build':
        print('built', build())
        return 0
    log = os.path.join(paths.BASE, 'work', 'sound', a.set + '.ymlog.txt')
    rom = os.path.join(paths.BASE, 'work', 'rom', a.set + '.ymz.bin')
    ev = events_from_log(log, a.seconds)
    n = int(a.seconds * RATE)
    out = os.path.join(paths.BASE, 'work', 'sound', a.set + '.ref.i32')
    arr = run(rom, ev, n, out)
    print('%s: %d events, %d samples, peak %d' % (a.set, len(ev), len(arr) // 2, max(abs(x) for x in arr)))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
